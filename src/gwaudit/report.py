"""Render reports/report.md from reports/results.json and the tables.

Every number in the report is read from results.json (written by
gwaudit.analysis), so the text cannot drift from the calculation.

Run: python -m gwaudit.report
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
REP = ROOT / "reports"
R = json.loads((REP / "results.json").read_text())
PREP = json.loads((ROOT / "data" / "processed" / "prepare_summary.json").read_text())
LOG = pd.read_csv(ROOT / "data" / "processed" / "exclusion_log.csv")


def f2(x, nd=2):
    return "n/a" if x is None else f"{x:.{nd}f}"


def coverage_table():
    rows = []
    for fam, lab in [("arsenic", "Arsenic (dissolved, µg/L)"), ("nitrate_as_n", "Nitrate as N (dissolved, mg/L)")]:
        c = R[fam]["coverage"]
        spw = c["samples_per_well"]
        rows.append(f"| {lab} | {c['rows']} | {c['wells']} | {spw['1']} / {spw['2']} / {spw['3-5']} / {spw['6+']} | "
                    f"{c['first_date']} to {c['last_date']} | {c['censored']} ({100*c['censored_share']:.1f}%) | {c['detected_without_limit']} |")
    return ("| Constituent | Routine samples | Wells | Wells with 1 / 2 / 3–5 / 6+ samples | Dates | Non-detects | Detected rows with no limit |\n"
            "|---|---|---|---|---|---|---|\n" + "\n".join(rows))


def period_table(fam):
    p = R[fam]["pooled_vs_cohort"]
    rows = []
    for kind, label in [("pooled", "All samples (pooled)"), ("one_per_well", "One sample per well"), ("cohort", "Consistent cohort")]:
        e, l = p[f"{kind}_early"], p[f"{kind}_late"]
        rows.append(f"| {label} | {e['wells']} | {e['n']} | {f2(e['km_median'])} | {l['wells']} | {l['n']} | {f2(l['km_median'])} |")
    return ("| Summary | Early wells | Early n | Early KM median | Late wells | Late n | Late KM median |\n"
            "|---|---|---|---|---|---|---|\n" + "\n".join(rows))


def paired_block(fam):
    pc = R[fam]["paired_change"]
    st = pc["sign_test"]; bw = pc["bootstrap_wells"]; w = pc.get("wilcoxon_both_detected", {})
    return (f"- Cohort wells: {pc['n_pairs']} (median {pc['median_years_apart']} years between the two samples).\n"
            f"- Direction of change, same well: **{pc['decline']} decline, {pc['increase']} increase, {pc['indeterminate']} indeterminate** "
            f"(indeterminate means at least one of the two results is a non-detect whose interval overlaps the other).\n"
            f"- Share declining among the {st['determinate']} determinate wells: {st['share_declining']:.3f} "
            f"(exact binomial 95% CI {st['ci95_share_declining'][0]:.3f}–{st['ci95_share_declining'][1]:.3f}; sign test p = {st['p_two_sided']:.3f}).\n"
            f"- Share declining among all cohort wells: {bw['share_declining_all_pairs']:.3f} "
            f"(well-level bootstrap 95% CI {bw['share_declining_ci95'][0]:.3f}–{bw['share_declining_ci95'][1]:.3f}, {bw['n_boot']} resamples, seed {bw['seed']}).\n"
            f"- Among the {pc['both_detected']} wells with both results detected, the median late/early ratio is "
            f"{w.get('median_ratio_late_over_early', float('nan')):.3f} (Wilcoxon signed-rank p = {w.get('p_two_sided', float('nan')):.3f}).\n"
            f"- Substitution sensitivity (share declining if non-detects are set to zero / half the limit / the limit): "
            f"{pc['substitution_sensitivity']['zero']['share_declining']:.3f} / {pc['substitution_sensitivity']['half']['share_declining']:.3f} / "
            f"{pc['substitution_sensitivity']['limit']['share_declining']:.3f}.")


def main():
    a, n = R["arsenic"], R["nitrate_as_n"]
    ak, nk = a["per_well_kendall"], n["per_well_kendall"]
    ar, nr = a["replicate_precision"], n["replicate_precision"]
    lim = pd.DataFrame(a["limits_by_year"])
    md = f"""# Groundwater Audit: reference analysis report

Question: *Did measured concentrations of dissolved arsenic and of dissolved
nitrate decline at repeatedly sampled wells in San Bernardino County,
California, between 2000–2011 and 2012–2023?*

This report is generated by `python -m gwaudit.report` from `reports/results.json`.
Source data: Water Quality Portal snapshot described in `data/raw/manifest.json`
(USGS NWIS records, {PREP['raw_rows']} result rows, downloaded 2026-10-07).

## 1. What was kept and what was excluded

| Step | Rule | Rows before | Rows after | Removed |
|---|---|---|---|---|
""" + "\n".join(f"| {r.step} | {r.rule} | {r.rows_before} | {r.rows_after} | {r.rows_removed} |" for r in LOG.itertuples()) + f"""

Non-groundwater media removed: {PREP['media_removed']}. Activity types removed:
{PREP['activity_type_removed']} (field replicates, {PREP['replicate_rows']} rows, are kept
separately for precision). The nitrate rows reported in "mg/l asNO3" (USGS code
71851) are NWIS re-expressions of the "mg/l as N" rows (00618): on
{PREP['derived_duplicate_ratio_check']['71851/00618']['n_pairs']} paired activities the ratio is
{PREP['derived_duplicate_ratio_check']['71851/00618']['ratio_min']}–{PREP['derived_duplicate_ratio_check']['71851/00618']['ratio_max']}
(expected {PREP['derived_duplicate_ratio_check']['71851/00618']['expected']}, deviations are rounding), so they were dropped rather
than converted and double counted. Nitrate-plus-nitrite (00631) is a different
chemical definition and was kept as a separate family; it never occurs without
00618 in this snapshot, so it was not needed for the trend question.

## 2. Coverage

{coverage_table()}

![coverage](figures/fig1_coverage.png)

Most wells were sampled once. The median spacing between repeat samples at
the same well is {a['coverage']['median_days_between_samples_same_well']:.0f} days for arsenic and
{n['coverage']['median_days_between_samples_same_well']:.0f} days for nitrate. Result status is
"Preliminary" for {a['coverage']['status'].get('Preliminary', 0)} arsenic rows and
{n['coverage']['status'].get('Preliminary', 0)} nitrate rows; these are USGS records not yet
through final review and are retained with that flag. Arsenic analyses moved from an
unnamed laboratory (2000–2006) to a contract laboratory (2005–2012) and the USGS
National Water Quality Laboratory (2007 onward); the reporting limit for non-detects
fell from about {lim.loc[lim['year'] <= 2005, 'median'].median():.1f} µg/L before 2006 to
{lim.loc[lim['year'] >= 2013, 'median'].median():.1f} µg/L after 2012 (Figure 2).

![limits](figures/fig2_limits.png)

Metadata gaps: {a['coverage']['detected_without_limit']} detected arsenic rows and
{n['coverage']['detected_without_limit']} detected nitrate rows carry no reporting limit;
{a['coverage']['time_missing']} arsenic rows have no sample time; most field replicates cannot be
paired with a routine sample on the same date in this snapshot (arsenic: {ar['pairs']} pairs,
nitrate: {nr['pairs']} pairs), so laboratory-plus-field precision is only roughly known
(median relative percent difference {ar.get('median_rpd_pct', 'n/a')}% for arsenic,
{nr.get('median_rpd_pct', 'n/a')}% for nitrate).

## 3. Target quantity and unit of analysis

For each constituent: the direction and size of change in observed dissolved
concentration *at the same well* between the early period (2000–2011) and the
late period (2012–2023), using the last routine groundwater sample of each
period, over wells sampled in both periods (the consistent cohort). The
independent unit is the well. Non-detects are intervals [0, limit]; a change is
called only when the two intervals do not overlap. Medians are Kaplan–Meier
(KM) estimates that use the limits without substitution.

## 4. Pooled summaries versus the consistent cohort

### Arsenic (µg/L)

{period_table('arsenic')}

### Nitrate as N (mg/L)

{period_table('nitrate_as_n')}

![pooled vs cohort](figures/fig4_pooled_vs_cohort.png)

The pooled arsenic median rises from {f2(a['pooled_vs_cohort']['pooled_early']['km_median'])} to
{f2(a['pooled_vs_cohort']['pooled_late']['km_median'])} µg/L, and the pooled nitrate median falls from
{f2(n['pooled_vs_cohort']['pooled_early']['km_median'])} to {f2(n['pooled_vs_cohort']['pooled_late']['km_median'])} mg/L.
Neither is a change at wells: only {a['pooled_vs_cohort']['cohort_wells']} of the arsenic wells and
{n['pooled_vs_cohort']['cohort_wells']} of the nitrate wells appear in both periods, and the
cohort medians are nearly unchanged ({f2(a['pooled_vs_cohort']['cohort_early']['km_median'])} to
{f2(a['pooled_vs_cohort']['cohort_late']['km_median'])} µg/L; {f2(n['pooled_vs_cohort']['cohort_early']['km_median'])} to
{f2(n['pooled_vs_cohort']['cohort_late']['km_median'])} mg/L). The pooled differences reflect which
wells were sampled in each period (the late period includes more high-arsenic
wells and more low-nitrate wells), not a change in the water at any well.

## 5. Within-well change in the consistent cohort

![cohort pairs](figures/fig3_cohort_pairs.png)

### Arsenic

{paired_block('arsenic')}

### Nitrate as N

{paired_block('nitrate_as_n')}

Per-well monotonic trend (interval-aware Kendall S) for wells with six or more
samples: arsenic {ak['wells_with_6plus_samples']} wells, {ak['tau_le_-0.5']} with tau ≤ −0.5 and
{ak['tau_ge_0.5']} with tau ≥ 0.5 (median tau {ak['median_tau']}); nitrate {nk['wells_with_6plus_samples']} wells,
{nk['tau_le_-0.5']} with tau ≤ −0.5 and {nk['tau_ge_0.5']} with tau ≥ 0.5 (median tau {nk['median_tau']}).

## 6. Interpretation

**Nitrate.** At the {n['pooled_vs_cohort']['cohort_wells']} wells sampled in both periods, declines
({n['paired_change']['decline']}) and increases ({n['paired_change']['increase']}) are about equally common and
the median within-well ratio is {n['paired_change']['wilcoxon_both_detected']['median_ratio_late_over_early']:.2f}. The data do not
support a decline in measured nitrate at repeatedly sampled wells. The lower pooled
median in the late period is a change in which wells were sampled.

**Arsenic.** At the {a['pooled_vs_cohort']['cohort_wells']} cohort wells, declines outnumber increases
({a['paired_change']['decline']} vs {a['paired_change']['increase']}, sign test p = {a['paired_change']['sign_test']['p_two_sided']:.3f}) and the
median within-well ratio among detected pairs is {a['paired_change']['wilcoxon_both_detected']['median_ratio_late_over_early']:.3f}, a
change of about {100*(1-a['paired_change']['wilcoxon_both_detected']['median_ratio_late_over_early']):.0f}%. This shift is statistically
detectable but small: it is well inside the replicate precision of the measurements
(median relative percent difference {ar.get('median_rpd_pct', 'n/a')}% on {ar['pairs']} pairs), the
laboratory and reporting limit changed between the periods, and
{a['paired_change']['indeterminate']} wells cannot be classified because an early non-detect at 1–2 µg/L
overlaps the late result. The defensible statement is that measured arsenic at the
cohort wells was, on average, slightly lower in the late period, by an amount
comparable to measurement variability, with no evidence of a widespread decline.

Neither result supports a statement about remediation, basin-wide improvement,
or health risk. The cohort is the set of wells the USGS and the Mojave Water
Agency chose to resample, which is not a random sample of wells in the county.

## 7. Limitations attached to these claims

- Most wells have one sample; the cohort is a minority of wells and its selection is not documented in the snapshot.
- The early period is dominated by one contract laboratory for 2005–2012 and the reporting limit changed by an order of magnitude; a method shift could produce a small apparent change.
- Replicate pairing is largely unavailable, so precision is estimated from a handful of pairs.
- Period summaries use one sample per well per period; within-period variability at a well is not used.
- "Preliminary" USGS records are included; final review could change individual values.
"""
    (REP / "report.md").write_text(md)
    print(f"wrote {REP / 'report.md'} ({len(md.splitlines())} lines)")


if __name__ == "__main__":
    main()
